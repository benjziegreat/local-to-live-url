// Minimal Excel (.xlsx) writer: one worksheet with a title block, a bold header row and
// data rows. No dependencies: the workbook parts are packed in an uncompressed ZIP.

export interface XlsxColumn {
  key: string;
  label: string;
}

export interface XlsxSheet {
  name: string;
  /** Lines printed above the table (first one in large bold) */
  title?: string[];
  columns: XlsxColumn[];
  rows: Record<string, unknown>[];
  /** Label/value pairs printed under the table */
  summary?: { label: string; value: unknown }[];
}

const enc = new TextEncoder();

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(data: Uint8Array): number {
  let c = 0xffffffff;
  for (let i = 0; i < data.length; i++) c = CRC_TABLE[(c ^ data[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** Store-only ZIP archive. */
function zip(files: { name: string; data: Uint8Array }[]): Blob {
  const parts: Uint8Array[] = [];
  const central: Uint8Array[] = [];
  let offset = 0;
  const now = new Date();
  const time = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1);
  const date = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();
  for (const f of files) {
    const name = enc.encode(f.name);
    const crc = crc32(f.data);
    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true);
    local.setUint16(4, 20, true);
    local.setUint16(6, 0x0800, true);
    local.setUint16(8, 0, true);
    local.setUint16(10, time, true);
    local.setUint16(12, date, true);
    local.setUint32(14, crc, true);
    local.setUint32(18, f.data.length, true);
    local.setUint32(22, f.data.length, true);
    local.setUint16(26, name.length, true);
    local.setUint16(28, 0, true);
    parts.push(new Uint8Array(local.buffer), name, f.data);

    const cd = new DataView(new ArrayBuffer(46));
    cd.setUint32(0, 0x02014b50, true);
    cd.setUint16(4, 20, true);
    cd.setUint16(6, 20, true);
    cd.setUint16(8, 0x0800, true);
    cd.setUint16(10, 0, true);
    cd.setUint16(12, time, true);
    cd.setUint16(14, date, true);
    cd.setUint32(16, crc, true);
    cd.setUint32(20, f.data.length, true);
    cd.setUint32(24, f.data.length, true);
    cd.setUint16(28, name.length, true);
    cd.setUint32(42, offset, true);
    central.push(new Uint8Array(cd.buffer), name);
    offset += 30 + name.length + f.data.length;
  }
  const cdSize = central.reduce((n, p) => n + p.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true);
  end.setUint16(8, files.length, true);
  end.setUint16(10, files.length, true);
  end.setUint32(12, cdSize, true);
  end.setUint32(16, offset, true);
  return new Blob([...parts, ...central, new Uint8Array(end.buffer)] as BlobPart[], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
}

const esc = (s: string) =>
  s
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

function colName(i: number): string {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

const PERCENT = /^-?\d+(\.\d+)?%$/;
const SIGNED = /^[+-]\d+(\.\d+)?$/;

/** Styles: 0 normal, 1 header (bold, shaded, bordered), 2 title (bold 14pt), 3 bold, 4 bordered, 5 bordered percent. */
function cell(ref: string, value: unknown, style = 0): string {
  // Data cells: "85.2%" becomes a real percentage and "+12.5" a number, so Excel can sort and compute.
  if (style === 4 && typeof value === 'string') {
    if (PERCENT.test(value)) return `<c r="${ref}" s="5"><v>${Number(value.slice(0, -1)) / 100}</v></c>`;
    if (SIGNED.test(value)) value = Number(value);
  }
  const s = style ? ` s="${style}"` : '';
  if (value === null || value === undefined || value === '') return style ? `<c r="${ref}"${s}/>` : '';
  if (typeof value === 'number' && Number.isFinite(value)) return `<c r="${ref}"${s}><v>${value}</v></c>`;
  return `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${esc(String(value))}</t></is></c>`;
}

function sheetXml(sheet: XlsxSheet): string {
  const rows: string[] = [];
  let r = 1;
  sheet.title?.forEach((line, i) => {
    rows.push(`<row r="${r}">${cell(`A${r}`, line, i === 0 ? 2 : 0)}</row>`);
    r++;
  });
  if (sheet.title?.length) r++;
  const headerRow = r;
  rows.push(`<row r="${r}">${sheet.columns.map((c, i) => cell(`${colName(i)}${r}`, c.label, 1)).join('')}</row>`);
  r++;
  for (const row of sheet.rows) {
    rows.push(`<row r="${r}">${sheet.columns.map((c, i) => cell(`${colName(i)}${r}`, row[c.key], 4)).join('')}</row>`);
    r++;
  }
  if (sheet.summary?.length) {
    r++;
    for (const s of sheet.summary) {
      rows.push(`<row r="${r}">${cell(`A${r}`, s.label, 3)}${cell(`B${r}`, s.value)}</row>`);
      r++;
    }
  }
  // Column widths from the longest value (capped)
  const widths = sheet.columns.map((c) => {
    const longest = Math.max(c.label.length, ...sheet.rows.slice(0, 500).map((row) => String(row[c.key] ?? '').length));
    return Math.min(60, Math.max(6, longest + 2));
  });
  const cols = widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const last = `${colName(sheet.columns.length - 1)}${Math.max(headerRow, headerRow + sheet.rows.length)}`;
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' +
    `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${headerRow}" topLeftCell="A${headerRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` +
    `<cols>${cols}</cols><sheetData>${rows.join('')}</sheetData>` +
    `<autoFilter ref="A${headerRow}:${last}"/>` +
    '</worksheet>'
  );
}

